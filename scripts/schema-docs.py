#!/usr/bin/env python3
"""Regenerates `docs/schema/` from the migrations.

Two things come out of it: the browsable Markdown tbls writes, and one `.dbml`
file. The Markdown answers "what does this column do"; the DBML is the one to
paste into dbdiagram.io when the question is "what is the shape of this",
because a diagram of fourteen tables with every column on it is a wall, not a
picture.

# Why the migrations and not a running server

The tables this documents are created by the files in
`apps/server/src/db/migration/sql/`, so replaying those is the shortest path
from source of truth to diagram — no build, no server to start and stop, no
port to be already in use. It was checked against a database the server itself
migrated: same tables, same indexes, byte-identical definitions.

# Why SQLite

Any of the three dialects would draw the same picture — the tables and the keys
between them are the same everywhere. SQLite is the one that needs nothing
running.
"""

import glob
import pathlib
import shutil
import sqlite3
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
MIGRATIONS = ROOT / "apps/server/src/db/migration/sql"
OUT = ROOT / "docs/schema"
IMAGE = "ghcr.io/k1low/tbls:v1.85.4"


def build_database(path: pathlib.Path) -> None:
    connection = sqlite3.connect(path)
    connection.execute("PRAGMA foreign_keys = ON")
    for file in sorted(glob.glob(str(MIGRATIONS / "*.sqlite.sql"))):
        connection.executescript(pathlib.Path(file).read_text(encoding="utf-8"))
    connection.commit()
    connection.close()


# Types SQLite reports, mapped to something dbdiagram draws sensibly. SQLite's
# own affinities are not wrong, they are just not what anybody writes.
DBML_TYPES = {"INTEGER": "integer", "TEXT": "text", "BLOB": "blob"}


def dbml_type(declared: str) -> str:
    return DBML_TYPES.get(declared.upper(), declared.lower() or "text")


def write_dbml(path: pathlib.Path) -> None:
    """Emits DBML for the schema, read back out of a migrated database.

    # Why not straight from the migration files

    `sql2dbml` reads DDL, and three of these migrations use `ALTER TABLE`, which
    it does not apply — pointing it at the files produces a `sessions` table
    missing two columns and says nothing about it. Reading the database after
    the migrations have run is the only version that cannot be quietly wrong.

    That also means no Node toolchain in CI for the sake of one text file.
    """
    with tempfile.TemporaryDirectory() as work_str:
        database = pathlib.Path(work_str) / "schema.db"
        build_database(database)
        connection = sqlite3.connect(database)
        connection.row_factory = sqlite3.Row

        tables = [
            row["name"]
            for row in connection.execute(
                "SELECT name FROM sqlite_master WHERE type = 'table'"
                " AND name NOT LIKE 'sqlite_%' AND name != 'seaql_migrations'"
                " ORDER BY name"
            )
        ]
        notes = table_notes()
        blocks: list[str] = [
            "// Generated by scripts/schema-docs.py. Do not edit.",
            "// Paste into https://dbdiagram.io to see it laid out.",
            "",
            "Project tessera {",
            "  database_type: 'SQLite'",
            "  Note: 'The same tables on PostgreSQL and MySQL; only the types differ.'",
            "}",
            "",
        ]
        references: list[str] = []

        for table in tables:
            columns = list(connection.execute(f"PRAGMA table_info('{table}')"))
            keys = {row["name"] for row in columns if row["pk"]}
            foreign = {
                row["from"]: (row["table"], row["to"], row["on_delete"])
                for row in connection.execute(f"PRAGMA foreign_key_list('{table}')")
            }
            unique = {
                columns_of(connection, index["name"])[0]
                for index in connection.execute(f"PRAGMA index_list('{table}')")
                if index["unique"] and len(columns_of(connection, index["name"])) == 1
            }

            lines = [f"Table {table} {{"]
            for row in columns:
                settings = []
                if row["name"] in keys:
                    settings.append("pk")
                if row["notnull"]:
                    settings.append("not null")
                # Not on a primary key: SQLite reports its implicit index as a
                # unique one, and `[pk, unique]` says the same thing twice.
                if row["name"] in unique and row["name"] not in keys:
                    settings.append("unique")
                suffix = f" [{', '.join(settings)}]" if settings else ""
                lines.append(f"  {row['name']} {dbml_type(row['type'])}{suffix}")
            if note := notes.get(table):
                lines.append("")
                lines.append(f"  Note: '{note.replace(chr(39), chr(39) * 2)}'")
            lines.append("}")
            blocks.append("\n".join(lines))
            blocks.append("")

            for column, (parent, parent_column, on_delete) in foreign.items():
                cascade = " [delete: cascade]" if (on_delete or "").upper() == "CASCADE" else ""
                references.append(
                    f"Ref: {table}.{column} > {parent}.{parent_column}{cascade}"
                )

        connection.close()
        blocks.extend(sorted(references))
        blocks.append("")
        path.write_text("\n".join(blocks), encoding="utf-8")


def columns_of(connection: sqlite3.Connection, index: str) -> list[str]:
    return [row["name"] for row in connection.execute(f"PRAGMA index_info('{index}')")]


def unquote(value: str) -> str:
    """Reads a single-quoted YAML scalar.

    The notes have to be quoted, because an unquoted scalar cannot contain
    `: ` and several of them do. Doubling is how YAML escapes a quote inside
    one, and this is the other half of what `write_dbml` does when it writes
    them back out.
    """
    if len(value) >= 2 and value.startswith("'") and value.endswith("'"):
        return value[1:-1].replace("''", "'")
    return value


def table_notes() -> dict[str, str]:
    """The per-table descriptions from `.tbls.yml`, so they are written once.

    Parsed by hand rather than with a YAML library: this script otherwise needs
    nothing that is not in the standard library, and CI would have to install it.
    """
    notes: dict[str, str] = {}
    table: str | None = None
    for line in (ROOT / ".tbls.yml").read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if stripped.startswith("- table:"):
            table = stripped.removeprefix("- table:").strip()
        elif stripped.startswith("tableComment:") and table:
            notes[table] = unquote(stripped.removeprefix("tableComment:").strip())
            table = None
    return notes


def main() -> int:
    if not shutil.which("docker"):
        print("docker is needed to run tbls", file=sys.stderr)
        return 1

    with tempfile.TemporaryDirectory() as work_str:
        work = pathlib.Path(work_str)
        build_database(work / "schema.db")
        shutil.copy(ROOT / ".tbls.yml", work / ".tbls.yml")

        result = subprocess.run(
            [
                "docker", "run", "--rm",
                # Written as the invoking user, or the output arrives owned by
                # root and the next run cannot overwrite it.
                "--user", f"{__import__('os').getuid()}:{__import__('os').getgid()}",
                "-v", f"{work}:/work", "-w", "/work", IMAGE,
                "doc", "--rm-dist",
            ],
            capture_output=True,
            text=True,
            check=False,
        )
        if result.returncode != 0:
            print(result.stdout + result.stderr, file=sys.stderr)
            return result.returncode

        if OUT.exists():
            shutil.rmtree(OUT)
        shutil.copytree(work / "out", OUT)

    write_dbml(OUT / "tessera.dbml")

    # `schema.json` is tbls's own machine-readable dump. It carries the path of
    # the temporary database it was built from, so it changes on every run for
    # a reason that has nothing to do with the schema — which would make the
    # drift check fire constantly and teach everyone to ignore it.
    (OUT / "schema.json").unlink(missing_ok=True)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
